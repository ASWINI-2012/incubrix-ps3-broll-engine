def generate_scene_image(
    generator: Any,
    scene: dict[str, Any],
    folder: Path,
    *,
    job_id: str,
    visual_style: str,
    ratio: str,
    avoid: list[str],
) -> dict[str, Any]:
    prompt = image_prompt(scene, visual_style)
    destination = folder / "generated_images" / f"{scene['scene_id']}.png"
    try:
        generated = generator.generate(
            prompt,
            destination,
            seed=scene_seed(job_id, scene["scene_id"]),
            ratio=ratio,
            avoid=avoid,
        )
    except ImageGenerationError as error:
        raise JobProcessingError(
            "image_generation_failed",
            f"Image generation failed for {scene['scene_id']} ({error.code}): {error.message}",
        ) from error
    image_path = Path(generated["path"])
    if not image_path.is_file() or image_path.stat().st_size == 0:
        raise JobProcessingError(
            "image_generation_failed",
            f"Image generation failed for {scene['scene_id']}: the backend did not create a valid image file.",
        )
    prompt_used = generated.get("prompt", prompt)
    model = str(generated.get("model") or generator.model)
    scene["image_prompt"] = prompt_used
    scene["clip"] = {
        "provider": "AI image generation",
        "provider_source": "generated_for_job",
        "provider_mode": "generated_images",
        "asset_id": scene["scene_id"],
        "source_url": None,
        "download_url": None,
        "creator": f"Generated by {model}",
        "source_description": prompt_used,
        "license_name": None,
        "license_url": None,
        "attribution_required": "Review the selected model's licence and usage terms.",
        "usage_rights_confirmed": None,
        "relevance_score": None,
        "selection_reason": "A separate image was generated from this scene's own narration and visual style.",
        "matching_method": "scene-specific image-generation prompt",
        "search_queries_tried": [],
        "source_width": int(generated.get("width") or 0),
        "source_height": int(generated.get("height") or 0),
        "fallback_warnings": [],
        "media_type": "image",
        "image_url": f"/api/v1/jobs/{job_id}/images/{image_path.name}",
        "model": model,
        "seed": int(generated.get("seed", -1)),
        "file_path": str(image_path),
    }
    return {
        "scene_id": scene["scene_id"],
        "file": image_path.relative_to(folder).as_posix(),
        "prompt": prompt_used,
        "model": model,
        "seed": scene["clip"]["seed"],
        "width": scene["clip"]["source_width"],
        "height": scene["clip"]["source_height"],
    }


def split_script(script: str) -> list[dict[str, Any]]:
    script = clean_script_text(script)
    sentences = []
    # A sentence boundary may touch the next capitalized sentence ("hands.Medical")
    # when scripts are pasted or concatenated without whitespace. Keep common
    # title abbreviations such as "Dr. Smith" together.
    boundary = (
        r"(?<=[!?])(?:\s+|(?=[A-Z]))|"
        r"(?<!Dr)(?<!Mr)(?<!Mrs)(?<!Ms)(?<!Prof)(?<!Sr)(?<!Jr)(?<!St)"
        r"(?<!eg)(?<!ie)(?<=\.)(?:\s+|(?=[A-Z][A-Za-z]{1,}\b))|\n+"
    )
    for part in re.split(boundary, script.strip(), flags=re.IGNORECASE):
        cleaned = re.sub(r"\s+", " ", part).strip()
        if cleaned:
            sentences.extend(textwrap.wrap(cleaned, width=600, break_long_words=True))
    if not sentences:
        raise JobProcessingError("empty_script", "The script does not contain any scenes.")
    if len(sentences) > 100:
        raise JobProcessingError("too_many_scenes", "A script may produce at most 100 scenes.")
    scenes = []
    for index, text in enumerate(sentences, start=1):
        description, search_query = describe_scene(text)
        scenes.append({"scene_id": f"scene-{index:03d}", "text": text, "visual_description": description, "duration_seconds": None, "search_query": search_query})
    return scenes


def clean_script_text(script: str) -> str:
    """Remove title-only Markdown/header lines so headings are not spoken as narration."""
    cleaned = re.sub(r"(?im)^\s*(?:\*\*|__)?\s*title\s*:\s*.*?(?:\*\*|__)?\s*(?:\r?\n|$)", "", script)
    cleaned = re.sub(r"(?im)^\s{0,3}#{1,6}\s+title\s*:\s*.*(?:\r?\n|$)", "", cleaned)
    cleaned = re.sub(r"(?im)^\s*(?:\*\*|__)?\s*title\s*:\s*.*?(?:\*\*|__)?\s*(?=\S)", "", cleaned)
    return cleaned.strip()


def describe_scene(text: str) -> tuple[str, str]:
    useful = " ".join(query_terms(text, limit=10))
    if not useful:
        raise JobProcessingError("empty_scene", "The submitted scene does not contain searchable content.")
    # Keep the spoken sentence intact in scene.text, but use a short keyword phrase
    # for footage search. Narration is not appended to an existing visual prompt.
    return useful, useful


def _scene_visual_text(scene: dict[str, Any]) -> str:
    """Return only the visual prompt, deriving one from narration as a last resort."""
    visual_text = scene.get("search_query") or scene.get("visual_description") or scene.get("text", "")
    return re.sub(r"(?i)^footage illustrating:\s*", "", visual_text).strip()


def scene_search_queries(scene: dict[str, Any]) -> list[str]:
    """Build fallback variants from visual text only, never from narration as well."""
    primary_text = _scene_visual_text(scene)
    visual_texts = [primary_text]
    # A manually supplied visual description is another visual-only fallback. It
    # can enrich a short search_query but is never combined with scene narration.
    description = re.sub(r"(?i)^footage illustrating:\s*", "", scene.get("visual_description", "")).strip()
    if scene.get("search_query") and description and description.lower() != primary_text.lower():
        visual_texts.append(description)

    terms_by_text = [query_terms(visual_text, limit=30) for visual_text in visual_texts]
    variants = [" ".join(terms[:12]) for terms in terms_by_text if terms]
    for terms in terms_by_text:
        if not terms:
            continue
        # Use contiguous, scene-specific phrases as progressively narrower
        # provider searches. No prior job data or unrelated defaults enter.
        if len(terms) > 6:
            variants.extend(" ".join(terms[start:start + 6]) for start in range(1, min(len(terms) - 5, 4)))
            variants.append(" ".join(terms[-6:]))
        elif len(terms) >= 3:
            # Drop modifiers while retaining scene-specific terms. Adding
            # generic suffixes such as "footage" or "video" rarely broadens
            # catalogue coverage and produces near-duplicate requests.
            variants.append(" ".join((terms[0], terms[-1])))
            variants.append(" ".join(terms[-2:]))
        else:
            canonical = " ".join(terms)
            variants.append(canonical)
    return list(dict.fromkeys(query for query in variants if query))


def query_terms(text: str, limit: int = 8) -> list[str]:
    # Split stock-provider URL slugs (green-valley-sunrise) into searchable words.
    words = re.findall(r"[A-Za-z0-9]+", text.lower())
    useful = [word for word in words if word not in STOP_WORDS and len(word) > 2]
    ordered = list(dict.fromkeys(useful))
    return ordered[:limit]


def rank_score(scene_text: str, candidate_text: str) -> float:
    scene_words = set(query_terms(scene_text, limit=30))
    candidate_words = set(query_terms(candidate_text, limit=60))
    if not scene_words:
        return 0.0
    return len(scene_words & candidate_words) / len(scene_words)


def allocate_scene_timing(
    scenes: list[dict[str, Any]], total_duration: float
) -> list[dict[str, Any]]:
    weights = [
        float(scene.get("duration_seconds") or max(1, len(scene["text"].split())))
        for scene in scenes
    ]
    weight_sum = sum(weights)
    cursor = 0.0
    timed = []
    for index, (scene, weight) in enumerate(zip(scenes, weights)):
        duration = total_duration - cursor if index == len(scenes) - 1 else total_duration * weight / weight_sum
        timed.append(
            {
                **scene,
                "start_time": round(cursor, 3),
                "end_time": round(cursor + duration, 3),
                "duration_seconds": round(duration, 3),
            }
        )
        cursor += duration
    if timed:
        timed[-1]["end_time"] = round(total_duration, 3)
        timed[-1]["duration_seconds"] = round(
            timed[-1]["end_time"] - timed[-1]["start_time"], 3
        )
    return timed


def make_srt(scenes: list[dict[str, Any]]) -> str:
    def stamp(seconds: float) -> str:
        millis = max(0, round(seconds * 1000))
        hours, remainder = divmod(millis, 3_600_000)
        minutes, remainder = divmod(remainder, 60_000)
        secs, milliseconds = divmod(remainder, 1000)
        return f"{hours:02}:{minutes:02}:{secs:02},{milliseconds:03}"

    def caption_blocks(text: str) -> list[str]:
        lines = []
        current = ""
        for word in re.sub(r"\s+", " ", text).strip().split():
            parts = textwrap.wrap(word, width=42, break_long_words=True, break_on_hyphens=False)
            for part in parts:
                if current and len(current) + 1 + len(part) > 42:
                    lines.append(current)
                    current = part
                else:
                    current = f"{current} {part}".strip()
        if current:
            lines.append(current)
        return ["\n".join(lines[index:index + 2]) for index in range(0, len(lines), 2)]

    blocks = []
    subtitle_index = 1
    for scene in scenes:
        text = re.sub(r"\s+", " ", scene["text"]).strip()
        captions = caption_blocks(text)
        if not captions:
            continue
        weights = [max(1, len(caption.split())) for caption in captions]
        weight_sum = sum(weights)
        scene_duration = scene["end_time"] - scene["start_time"]
        elapsed = 0.0
        for index, (caption, weight) in enumerate(zip(captions, weights)):
            start = scene["start_time"] + elapsed
            duration = (
                scene_duration - elapsed
                if index == len(captions) - 1
                else scene_duration * weight / weight_sum
            )
            end = scene["end_time"] if index == len(captions) - 1 else start + duration
            blocks.append(
                f"{subtitle_index}\n{stamp(start)} --> {stamp(end)}\n{caption}\n"
            )
            subtitle_index += 1
            elapsed += duration
    return "\n".join(blocks)


def _assert_public_https_url(url: str) -> str:
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
        raise JobProcessingError("invalid_audio_url", "Audio URLs must use public HTTPS URLs.")
    try:
        addresses = {
            item[4][0]
            for item in socket.getaddrinfo(parsed.hostname, parsed.port or 443, type=socket.SOCK_STREAM)
        }
    except OSError as error:
        raise JobProcessingError("invalid_audio_url", "The audio URL host could not be resolved.") from error
    if not addresses or any(not ipaddress.ip_address(address).is_global for address in addresses):
        raise JobProcessingError("invalid_audio_url", "Audio URLs cannot point to private or local networks.")
    return url


def _bounded_download(url: str, destination: Path, max_bytes: int, allowed_hosts: set[str] | None = None) -> str:
    parsed = urlparse(url)
    if allowed_hosts:
        if parsed.scheme != "https" or parsed.hostname not in allowed_hosts:
            raise JobProcessingError("unsafe_media_url", "The media provider returned an unsupported download host.")
    else:
        _assert_public_https_url(url)
    total = 0
    with httpx.Client(timeout=float(os.getenv("PEXELS_TIMEOUT_SECONDS", "20")), follow_redirects=False) as client:
        try:
            with client.stream("GET", url) as response:
                response.raise_for_status()
                content_type = response.headers.get("content-type", "").split(";", 1)[0].lower()
                with destination.open("wb") as output:
                    for chunk in response.iter_bytes(64 * 1024):
                        total += len(chunk)
                        if total > max_bytes:
                            raise JobProcessingError("media_too_large", "The media file exceeds the configured size limit.")
                        output.write(chunk)
        except httpx.HTTPError as error:
            destination.unlink(missing_ok=True)
            raise JobProcessingError("media_download_failed", "The media download failed.") from error
    if total == 0:
        destination.unlink(missing_ok=True)
        raise JobProcessingError("empty_media", "The downloaded media file was empty.")
    return content_type


def download_audio_url(url: str, folder: Path) -> Path:
    temporary_path = folder / "audio-download"
    content_type = _bounded_download(url, temporary_path, audio_size_limit())
    parsed_extension = Path(urlparse(url).path).suffix.lower()
    extension_by_type = {
        "audio/mpeg": ".mp3",
        "audio/mp3": ".mp3",
        "audio/wav": ".wav",
        "audio/x-wav": ".wav",
        "audio/wave": ".wav",
        "audio/mp4": ".m4a",
        "audio/x-m4a": ".m4a",
    }
    extension = extension_by_type.get(content_type, parsed_extension)
    if (
        content_type not in extension_by_type
        and not (content_type == "application/octet-stream" and extension in {".mp3", ".wav", ".m4a"})
    ) or extension not in {".mp3", ".wav", ".m4a"}:
        temporary_path.unlink(missing_ok=True)
        raise JobProcessingError("invalid_audio_type", "The URL did not return an audio file.")
    destination = folder / f"narration{extension}"
    temporary_path.replace(destination)
    return destination


def probe_media(path: Path) -> dict[str, Any]:
    executable = os.getenv("FFPROBE_PATH", "ffprobe")
    if not shutil.which(executable) and not Path(executable).is_file():
        raise JobProcessingError(
            "ffprobe_missing",
            "FFprobe is required. Install FFmpeg and configure FFPROBE_PATH.",
        )
    command = [
        executable,
        "-v", "error",
        "-show_entries", "format=duration:stream=codec_type,codec_name,width,height",
        "-of", "json",
        str(path),
    ]
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=30, check=False)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise JobProcessingError("ffprobe_failed", "FFprobe could not inspect the media file.") from error
    if result.returncode:
        raise JobProcessingError("invalid_media", "The uploaded or downloaded media file is not valid media.")
    try:
        data = json.loads(result.stdout)
        duration = float(data.get("format", {}).get("duration", 0))
    except (ValueError, json.JSONDecodeError) as error:
        raise JobProcessingError("invalid_media", "FFprobe returned invalid media metadata.") from error
    max_duration = audio_duration_limit()
    if duration <= 0 or duration > max_duration:
        raise JobProcessingError(
            "invalid_audio_duration",
            f"Audio duration must be between 0 and {max_duration} seconds.",
        )
    streams = data.get("streams", [])
    if not any(stream.get("codec_type") == "audio" for stream in streams):
        raise JobProcessingError("missing_audio_stream", "The input file does not contain an audio stream.")
    return {"duration_seconds": duration, "streams": streams}


def _synthesize_with_espeak(script: str, destination: Path) -> tuple[str, str]:
    configured = os.getenv("ESPEAK_NG_PATH", "").strip()
    executable = configured or shutil.which("espeak-ng") or shutil.which("espeak")
    if not executable and os.name == "nt":
        program_files = Path(os.getenv("ProgramFiles", r"C:\Program Files"))
        candidate = program_files / "eSpeak NG" / "espeak-ng.exe"
        try:
            executable = str(candidate) if candidate.is_file() else None
        except OSError:
            executable = None
    if not executable:
        raise JobProcessingError(
            "tts_unavailable",
            "Local speech synthesis is unavailable. Install a system voice or configure ESPEAK_NG_PATH.",
        )
    voice = os.getenv("ESPEAK_NG_VOICE", "en-us")
    try:
        result = subprocess.run(
            [executable, "-v", voice, "-w", str(destination), clean_script_text(script)],
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise JobProcessingError("tts_failed", "The eSpeak NG speech engine could not synthesize narration.") from error
    if result.returncode or not destination.is_file() or destination.stat().st_size == 0:
        raise JobProcessingError("tts_failed", "The eSpeak NG speech engine produced no audio file.")
    return voice, "eSpeak NG"


def synthesize_speech(script: str, destination: Path, voice: str | None) -> tuple[str, str]:
    try:
        import pyttsx3
    except ImportError:
        return _synthesize_with_espeak(script, destination)
    try:
        engine = pyttsx3.init()
        if voice:
            available = engine.getProperty("voices")
            match = next((item for item in available if item.id == voice or item.name == voice), None)
            if match is None:
                raise JobProcessingError("voice_unavailable", "The selected local TTS voice is not installed.")
            engine.setProperty("voice", match.id)
        selected_voice = str(engine.getProperty("voice") or "system-default")
        engine.save_to_file(clean_script_text(script), str(destination))
        engine.runAndWait()
        engine.stop()
        if not destination.is_file() or destination.stat().st_size == 0:
            raise RuntimeError("pyttsx3 produced no audio")
        return selected_voice, "pyttsx3"
    except JobProcessingError:
        raise
    except Exception as error:
        logger.warning("System speech synthesis failed; trying eSpeak NG: %s", error)
        return _synthesize_with_espeak(script, destination)


def transcribe_audio(path: Path) -> tuple[str, str]:
    try:
        from faster_whisper import WhisperModel
    except ImportError as error:
        raise JobProcessingError(
            "transcription_unavailable",
            "Audio-only jobs need faster-whisper for transcription or must include a script/manual scenes.",
        ) from error
    try:
        model = WhisperModel(os.getenv("WHISPER_MODEL", "tiny"), device="cpu", compute_type="int8")
        segments, _ = model.transcribe(str(path), vad_filter=True)
        transcript = " ".join(segment.text.strip() for segment in segments).strip()
    except Exception as error:
        logger.exception("Audio transcription failed")
        raise JobProcessingError("transcription_failed", "Audio transcription failed.") from error
    if not transcript:
        raise JobProcessingError("transcription_empty", "No speech could be transcribed from the audio.")
    return transcript, "faster-whisper"


def _avoid_words(avoid: list[str]) -> set[str]:
    return {
        word
        for term in avoid
        for word in query_terms(term, limit=20)
    }


def _is_https_url(value: str | None) -> bool:
    if not isinstance(value, str) or not value.strip():
        return False
    try:
        parsed = urlparse(value.strip())
        return parsed.scheme == "https" and bool(parsed.hostname)
    except ValueError:
        return False


def _download_cache_path(asset: Any) -> Path:
    cache_root = Path(os.getenv("FOOTAGE_CACHE_DIR", str(media_library.root() / "download_cache"))).resolve()
    key = "\0".join((asset.provider, asset.asset_id, asset.download_url or ""))
    return cache_root / (hashlib.sha256(key.encode("utf-8")).hexdigest() + ".mp4")


def _get_verified_provider_file(provider: FootageProvider, asset: Any) -> tuple[Path, dict[str, Any]]:
    """Reuse only cached provider bytes that still pass FFprobe validation."""
    cached = _download_cache_path(asset)
    cached.parent.mkdir(parents=True, exist_ok=True)
    if cached.is_file():
        try:
            return cached, probe_video(cached)
        except JobProcessingError:
            cached.unlink(missing_ok=True)
    temporary = cached.with_suffix(f".{os.getpid()}.{uuid.uuid4().hex}.download")
    temporary.unlink(missing_ok=True)
    try:
        provider.download(asset, temporary)
        facts = probe_video(temporary)
        os.replace(temporary, cached)
        return cached, facts
    finally:
        temporary.unlink(missing_ok=True)


def select_footage(
    scene: dict[str, Any],
    avoid: list[str],
    used_ids: set[str],
    folder: Path,
    visual_style: str,
    provider: FootageProvider | None = None,
    job_id: str | None = None,
) -> dict[str, Any]:
    selected_provider = provider or get_footage_provider()
    avoid_words = _avoid_words(avoid)
    minimum_score = float(os.getenv("MIN_FOOTAGE_RELEVANCE", "0.30"))
    # Try one concise query and a small number of scene-specific alternatives;
    # this bounds public API traffic even for long scripts.
    queries = scene_search_queries(scene)[:3]
    attempts: list[str] = []
    failure_details: list[str] = []
    attempted_asset_ids: set[str] = set()

    for query in queries:
        attempts.append(query)

        query_scene = {**scene, "search_query": query}
        if job_id:
            query_scene["job_id"] = job_id
        try:
            candidates = selected_provider.search(query_scene, avoid, visual_style)
        except FootageProviderError as error:
            failure_details.append(f"{query}: provider search failed ({error.code}: {error.message})")
            continue

        ranked = []
        for asset in candidates:
            video_id = asset.asset_id
            if video_id in attempted_asset_ids:
                continue
            video_terms = set(query_terms(asset.matching_text, limit=60))
            if any(
                avoid_word in video_term or video_term in avoid_word
                for avoid_word in avoid_words
                for video_term in video_terms
            ):
                continue
            # Visual relevance is checked against provider-supplied source metadata
            # for every query before any candidate is downloaded or assigned.
            score = rank_score(query, asset.matching_text)
            query_term_set = set(query_terms(query, limit=30))
            # One coincidental keyword (for example "ocean") is too weak to
            # assign a clip. For single-term queries, require that term.
            if len(query_term_set & video_terms) < min(2, len(query_term_set)):
                continue
            if score >= minimum_score:
                ranked.append((score, video_id in used_ids, asset.provider_rank, video_id, asset))
        ranked.sort(key=lambda item: (item[1], -item[0], item[2], item[3]))
        if not ranked:
            if not candidates and selected_provider.mode == "demo":
                configured_mode = os.getenv("BROLL_PROVIDER", "auto").strip().lower()
                if configured_mode == "demo":
                    online_reason = "BROLL_PROVIDER=demo is local-only; no online provider was queried"
                elif configured_mode == "auto":
                    online_reason = "the configured public sources returned no results or were unavailable"
                else:
                    online_reason = "the local provider returned no online results"
                failure_details.append(f"{query}: {online_reason} and the local catalogue has no eligible match")
            elif not candidates:
                source_status = getattr(selected_provider, "fallback_warnings", [])
                reason = f"; source status: {', '.join(source_status)}" if source_status else ""
                failure_details.append(f"{query}: provider returned no candidates{reason}")
            else:
                failure_details.append(f"{query}: candidates did not meet the visual metadata relevance threshold ({minimum_score:.2f})")
            continue

        for score, _, _, video_id, asset in ranked:
            attempted_asset_ids.add(video_id)
            missing_rights = []
            for field in ("source_url", "creator", "license_name", "license_url", "attribution_required"):
                value = getattr(asset, field)
                if not isinstance(value, str) or not value.strip():
                    missing_rights.append(field)
            for field in ("source_url", "license_url"):
                value = getattr(asset, field)
                if value and not _is_https_url(value):
                    missing_rights.append(f"https {field}")
            if missing_rights:
                failure_details.append(f"{query}: asset {video_id} skipped; missing or invalid rights metadata ({', '.join(missing_rights)})")
                continue
            if not _is_https_url(asset.download_url):
                failure_details.append(f"{query}: asset {video_id} skipped; download URL must be a valid HTTPS URL")
                continue
            try:
                source_path, video_facts = _get_verified_provider_file(selected_provider, asset)
            except (FootageProviderError, JobProcessingError, OSError) as error:
                code = getattr(error, "code", "download_failed")
                detail = getattr(error, "message", str(error))
                failure_details.append(f"{query}: asset {video_id} failed download/video validation ({code}: {detail})")
                continue
            used_ids.add(video_id)
            scene["search_query"] = query
            scene["clip"] = {
                "provider": asset.provider,
                "provider_source": "footage_provider_result",
                "provider_mode": selected_provider.mode,
                "asset_id": video_id,
                "source_url": asset.source_url,
                "download_url": asset.download_url,
                "creator": asset.creator,
                "source_description": asset.source_description,
                "license_name": asset.license_name,
                "license_url": asset.license_url,
                "attribution_required": asset.attribution_required,
                # Provider licence metadata is not the same as an explicit
                # per-asset rights confirmation; leave this unknown in reports.
                "usage_rights_confirmed": None,
                "relevance_score": round(score, 4),
                "selection_reason": "Provider source metadata matched the query; downloaded file type and video streams were validated.",
                "matching_method": selected_provider.matching_method,
                "search_queries_tried": attempts.copy(),
                "source_width": video_facts["width"],
                "source_height": video_facts["height"],
                "fallback_warnings": list(dict.fromkeys([*asset.warnings, *getattr(selected_provider, "fallback_warnings", [])])),
                "file_path": str(source_path),
            }
            return scene

    # The local catalogue is a fallback after the online providers have exhausted
    # the scene's own concise queries. Ineligible/review-required entries are
    # excluded by match_scene and can never be selected here.
    for query in queries:
        local = media_library.match_scene(query, used_ids)
        if not local:
            continue
        source_path = media_library.root() / local["path"]
        if not source_path.is_file():
            continue
        used_ids.add(local["id"])
        scene["search_query"] = query
        scene["clip"] = {"provider": local.get("provider"), "provider_source": local.get("provider_source"), "provider_mode": "local", "asset_id": local["id"], "source_url": local.get("source_url"), "creator": local.get("creator"), "source_description": local.get("caption"), "license_name": local.get("license_name"), "license_url": local.get("license_url"), "attribution_required": local.get("attribution_required"), "usage_rights_confirmed": local.get("usage_rights_confirmed"), "relevance_score": local["relevance_score"], "selection_reason": "Reviewed local catalogue metadata matched after public provider searches found no eligible clip.", "matching_method": "local-catalogue-keyword-overlap", "search_queries_tried": attempts.copy(), "source_width": local.get("validation", {}).get("width"), "source_height": local.get("validation", {}).get("height"), "fallback_warnings": failure_details.copy(), "file_path": str(source_path)}
        return scene

    details = "; ".join(dict.fromkeys(failure_details)) or "no usable local or provider candidates were returned"
    raise JobProcessingError(
        "no_footage_found",
        f"No sufficiently relevant, downloadable, rights-documented video was found for {scene['scene_id']}: {scene.get('visual_description') or scene['text']}. Queries tried in order: {', '.join(attempts)}. Reasons: {details}.",
    )


def _render_ratio(
    scenes: list[dict[str, Any]],
    audio_path: Path,
    folder: Path,
    ratio: str,
    captions_enabled: bool,
) -> dict[str, Any]:
    ffmpeg = os.getenv("FFMPEG_PATH", "ffmpeg")
    if not shutil.which(ffmpeg) and not Path(ffmpeg).is_file():
        raise JobProcessingError("ffmpeg_missing", "FFmpeg is required. Install FFmpeg and configure FFMPEG_PATH.")
    dimensions = {"16:9": (1920, 1080), "9:16": (1080, 1920), "1:1": (1080, 1080)}
    width, height = dimensions[ratio]
    segment_paths: list[Path] = []
    generated_images = all(scene.get("clip", {}).get("provider_mode") == "generated_images" for scene in scenes)
    transition = min(0.25, min(float(scene["duration_seconds"]) for scene in scenes) * 0.4) if generated_images and len(scenes) > 1 else 0
    for index, scene in enumerate(scenes):
        clip_path = Path(scene["clip"]["file_path"])
        segment_path = folder / f"{ratio.replace(':', 'x')}.segment-{index:03d}.mp4"
        if generated_images:
            try:
                with Image.open(clip_path) as image:
                    image.verify()
                with Image.open(clip_path) as image:
                    scene["clip"]["source_width"] = image.width
                    scene["clip"]["source_height"] = image.height
            except (OSError, ValueError) as error:
                raise JobProcessingError("image_validation_failed", f"Generated image for {scene['scene_id']} could not be decoded.") from error
            duration = float(scene["duration_seconds"]) + (transition if index > 0 else 0)
            vf = (
                f"scale={width}:{height}:force_original_aspect_ratio=increase,"
                f"crop={width}:{height},zoompan=z='min(zoom+0.0005,1.06)':"
                f"x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s={width}x{height}:fps=30,"
                "setsar=1,format=yuv420p"
            )
            command = [
                ffmpeg, "-y", "-hide_banner", "-loglevel", "error",
                "-loop", "1", "-framerate", "30", "-i", str(clip_path),
                "-t", f"{duration:.3f}", "-vf", vf, "-an", "-c:v", "libx264",
                "-preset", "veryfast", "-crf", "23", "-pix_fmt", "yuv420p",
                "-movflags", "+faststart", str(segment_path),
            ]
        else:
            probe = probe_video(clip_path)
            scene["clip"]["source_width"] = probe["width"]
            scene["clip"]["source_height"] = probe["height"]
            vf = (
                f"scale={width}:{height}:force_original_aspect_ratio=increase,"
                f"crop={width}:{height},setsar=1,fps=30,format=yuv420p"
            )
            command = [
                ffmpeg, "-y", "-hide_banner", "-loglevel", "error",
                "-stream_loop", "-1", "-i", str(clip_path),
                "-map", "0:v:0", "-t", f"{scene['duration_seconds']:.3f}",
                "-vf", vf, "-an", "-c:v", "libx264", "-preset", "veryfast",
                "-crf", "23", "-movflags", "+faststart", str(segment_path),
            ]
        _run_ffmpeg(command, "A footage segment could not be rendered.")
        segment_paths.append(segment_path)

    video_only = folder / f"{ratio.replace(':', 'x')}.silent.mp4"
    if generated_images and len(segment_paths) > 1:
        inputs = [item for path in segment_paths for item in ("-i", path.name)]
        filters = []
        previous = "0:v"
        for index in range(1, len(segment_paths)):
            target = f"v{index}"
            offset = sum(float(item["duration_seconds"]) for item in scenes[:index]) - transition
            filters.append(
                f"[{previous}][{index}:v]xfade=transition=fade:duration={transition:.3f}:offset={offset:.3f}[{target}]"
            )
            previous = target
        _run_ffmpeg(
            [ffmpeg, "-y", "-hide_banner", "-loglevel", "error", *inputs,
             "-filter_complex", ";".join(filters), "-map", f"[{previous}]", "-an",
             "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-pix_fmt", "yuv420p",
             "-movflags", "+faststart", video_only.name],
            "The generated image scenes could not be joined with transitions.", cwd=folder,
        )
    else:
        concat_list = folder / f"{ratio.replace(':', 'x')}.concat.txt"
        concat_list.write_text("".join(f"file '{path.name}'\n" for path in segment_paths), encoding="utf-8")
        _run_ffmpeg(
            [ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", concat_list.name,
             "-c", "copy", "-movflags", "+faststart", video_only.name],
            "The rendered footage segments could not be joined.", cwd=folder,
        )
    _assert_video_has_visible_content(video_only)
    name = f"video_{ratio.replace(':', 'x')}.mp4"
    output = folder / name
    command = [ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-i", video_only.name, "-i", audio_path.name]
    if captions_enabled:
        subtitle_path = "captions.srt".replace("\\", "/")
        command += ["-vf", f"subtitles={subtitle_path}:force_style='FontName=Arial,FontSize=22,Outline=2,Shadow=1,Alignment=2'"]
    command += [
        "-map", "0:v:0", "-map", "1:a:0", "-c:v", "libx264", "-preset", "veryfast",
        "-crf", "23", "-c:a", "aac", "-b:a", "192k", "-shortest", "-r", "30",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", output.name,
    ]
    _run_ffmpeg(command, "Final video rendering failed.", cwd=folder)
    metadata = probe_video(output)
    if metadata["width"] != width or metadata["height"] != height or not metadata["has_audio"]:
        raise JobProcessingError("output_validation_failed", "Rendered video streams did not match the requested format.")
    return {
        "file": name,
        "width": metadata["width"],
        "height": metadata["height"],
        "duration_seconds": metadata["duration_seconds"],
        "video_codec": metadata["video_codec"],
        "audio_codec": metadata["audio_codec"],
        "source_resolution_note": (
            "Output dimensions are the rendered canvas; generated image resolutions are recorded per scene in the timeline."
            if generated_images else
            "Output dimensions are the rendered canvas; individual source clip resolutions are recorded in the timeline."
        ),
    }


def _run_ffmpeg(command: list[str], message: str, cwd: Path | None = None) -> None:
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=1800, check=False, cwd=cwd)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise JobProcessingError("ffmpeg_failed", message) from error
    if result.returncode:
        logger.error("FFmpeg failed with exit code %s: %s", result.returncode, result.stderr[-4000:])
        raise JobProcessingError("ffmpeg_failed", message)


def _assert_video_has_visible_content(path: Path) -> None:
    """Reject black-screen renders instead of shipping caption-only output."""
    executable = os.getenv("FFMPEG_PATH", "ffmpeg")
    command = [executable, "-hide_banner", "-i", str(path), "-vf", "blackdetect=d=0.25:pix_th=0.10", "-an", "-f", "null", "-"]
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=300, check=False)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise JobProcessingError("visual_validation_failed", "FFmpeg could not verify visible footage in the rendered video.") from error
    if result.returncode:
        logger.error("Black-frame validation failed: %s", result.stderr[-4000:])
        raise JobProcessingError("visual_validation_failed", "FFmpeg could not verify visible footage in the rendered video.")
    durations = [float(value) for value in re.findall(r"black_duration:([0-9.]+)", result.stderr)]
    try:
        total = probe_video(path)["duration_seconds"]
    except JobProcessingError:
        raise
    black_fraction = sum(durations) / total if total else 1.0
    if black_fraction > float(os.getenv("MAX_BLACK_FRAME_FRACTION", "0.25")):
        raise JobProcessingError("black_video_output", f"Rendered footage is mostly black ({black_fraction:.0%} of frames). The source clip was rejected.")


def _remove_render_intermediates(folder: Path) -> None:
    patterns = (
        r"scene-\d{3}\.source\.mp4",
        r"(?:16x9|9x16|1x1)\.segment-\d{3}\.mp4",
        r"(?:16x9|9x16|1x1)\.silent\.mp4",
        r"(?:16x9|9x16|1x1)\.concat\.txt",
    )
    try:
        paths = list(folder.iterdir())
    except OSError:
        logger.warning("Could not inspect render intermediates for cleanup")
        return
    for path in paths:
        if path.is_file() and any(re.fullmatch(pattern, path.name) for pattern in patterns):
            try:
                path.unlink()
            except OSError:
                logger.warning("Could not remove render intermediate %s", path.name)


def probe_video(path: Path) -> dict[str, Any]:
    executable = os.getenv("FFPROBE_PATH", "ffprobe")
    if not shutil.which(executable) and not Path(executable).is_file():
        raise JobProcessingError("ffprobe_missing", "FFprobe is required to validate rendered files.")
    try:
        result = subprocess.run(
            [
                executable, "-v", "error", "-show_entries",
                "format=duration:stream=codec_type,codec_name,width,height",
                "-of", "json", str(path),
            ],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise JobProcessingError("output_validation_failed", "FFprobe could not validate the rendered video.") from error
    if result.returncode:
        raise JobProcessingError("output_validation_failed", "FFprobe could not validate the rendered video.")
    try:
        data = json.loads(result.stdout)
        streams = data.get("streams", [])
        video = next(stream for stream in streams if stream.get("codec_type") == "video")
        audio = next((stream for stream in streams if stream.get("codec_type") == "audio"), None)
        duration = float(data["format"]["duration"])
    except (ValueError, KeyError, StopIteration, json.JSONDecodeError) as error:
        raise JobProcessingError("output_validation_failed", "The rendered video is missing required media streams.") from error
    if duration <= 0:
        raise JobProcessingError("output_validation_failed", "The rendered video has no playable duration.")
    return {
        "duration_seconds": round(duration, 3),
        "width": int(video["width"]),
        "height": int(video["height"]),
        "video_codec": video.get("codec_name"),
        "audio_codec": audio.get("codec_name") if audio else None,
        "has_audio": audio is not None,
    }


def _load_requested_scenes(data: dict[str, Any]) -> list[dict[str, Any]]:
    if data.get("scenes"):
        scenes = []
        for index, item in enumerate(data["scenes"], start=1):
            description, generated_query = describe_scene(item["text"])
            visual_query = (item.get("search_query") or "").strip()
            scenes.append(
                {
                    "scene_id": f"scene-{index:03d}",
                    "text": item["text"],
                    "duration_seconds": item.get("duration_seconds"),
                    "visual_description": visual_query or description,
                    "search_query": visual_query or generated_query,
                }
            )
        return scenes
    return split_script(data["script"])


def _process(job_id: str, data: dict[str, Any], uploaded_audio: str | None) -> None:
    job = get_job(job_id)
    if not job:
        logger.error("Cannot process missing job %s", job_id)
        return
    output_root = Path(os.getenv("OUTPUT_DIR", "./outputs")).resolve()
    folder = output_root / job_id
    stages = {"audio": 15, "scenes": 25, "footage": 40, "rendering": 65}

    def stage(name: str, progress: int) -> None:
        update_job(job_id, status="processing", progress=progress, current_stage=name)

    try:
        folder.mkdir(parents=True, exist_ok=True)
        request = JobInput.model_validate(data)
        footage_provider = None
        image_generator = None
        if request.visual_source == "generated_images":
            try:
                image_generator = get_image_generator()
                image_model = image_generator.prepare()
            except ImageGenerationError as error:
                raise JobProcessingError(error.code, error.message) from error
            except Exception as error:
                raise JobProcessingError("image_backend_unavailable", "The configured image-generation backend could not be initialized.") from error
        else:
            try:
                footage_provider = get_footage_provider()
            except FootageProviderError as error:
                raise JobProcessingError(error.code, error.message) from error
        stage("audio", stages["audio"])
        if uploaded_audio:
            source = Path(uploaded_audio)
            audio_path = folder / f"narration{source.suffix.lower()}"
            shutil.copyfile(source, audio_path)
            audio_source_type = "uploaded_audio"
        elif request.audio_url:
            audio_path = download_audio_url(request.audio_url, folder)
            audio_source_type = "https_audio_url"
        else:
            audio_path = folder / "narration.wav"
            voice, narration_engine = synthesize_speech(clean_script_text(request.script or " ".join(scene.text for scene in request.scenes or [])), audio_path, request.voice)
            data["selected_voice"] = voice
            data["narration_provider"] = narration_engine
            audio_source_type = "local_text_to_speech"

        audio_metadata = probe_media(audio_path)
        audio_metadata["source_type"] = audio_source_type
        if request.script:
            scenes = split_script(request.script)
        elif request.scenes:
            scenes = _load_requested_scenes(data)
        else:
            transcript, transcription_method = transcribe_audio(audio_path)
            scenes = split_script(transcript)
            data["transcription_method"] = transcription_method

        scenes = allocate_scene_timing(scenes, audio_metadata["duration_seconds"])
        for scene in scenes:
            scene["search_query"] = scene.get("search_query") or " ".join(query_terms(scene["text"]))
        stage("scene_planning", stages["scenes"])
        generated_image_records: list[dict[str, Any]] = []
        if image_generator:
            for index, scene in enumerate(scenes, start=1):
                stage("image_generation", 30 + round(30 * index / len(scenes)))
                generated_image_records.append(generate_scene_image(
                    image_generator, scene, folder, job_id=job_id,
                    visual_style=request.visual_style, ratio=request.aspect_ratios[0],
                    avoid=request.avoid,
                ))
        else:
            used_ids: set[str] = set()
            stage("footage_search", stages["footage"])
            for index, scene in enumerate(scenes, start=1):
                stage("footage_search", 40 + round(20 * index / len(scenes)))
                select_footage(
                    scene, request.avoid, used_ids, folder, request.visual_style, footage_provider, job_id=job_id
                )

        (folder / "captions.srt").write_text(make_srt(scenes), encoding="utf-8")
        stage("rendering", stages["rendering"])
        videos = []
        for index, ratio in enumerate(request.aspect_ratios):
            stage("rendering", 65 + round(25 * index / len(request.aspect_ratios)))
            videos.append(_render_ratio(scenes, audio_path, folder, ratio, request.captions_enabled))
        selected_modes = {scene["clip"].get("provider_mode") for scene in scenes}
        effective_provider_mode = (
            "generated_images" if selected_modes == {"generated_images"}
            else "local" if selected_modes == {"local"}
            else footage_provider.mode
        )
        fallback_warnings = footage_provider.fallback_warnings if footage_provider else []
        image_generation_report = None
        if image_generator:
            image_generation_report = {
                "job_id": job_id,
                "backend": image_generator.name,
                "model": image_model,
                "images": [
                    {**image, "url": f"/api/v1/jobs/{job_id}/images/{Path(image['file']).name}"}
                    for image in generated_image_records
                ],
                "motion": "subtle zoom and crossfade transitions",
            }
            (folder / "image_generation_report.json").write_text(encode_json(image_generation_report), encoding="utf-8")
        timeline = {
            "job_id": job_id,
            "narration_duration_seconds": audio_metadata["duration_seconds"],
            "timing_method": "scene word-count weighting normalized to measured narration duration",
            "matching_method": "scene-specific image generation" if image_generator else "local-catalogue-keyword-overlap" if selected_modes == {"local"} else footage_provider.matching_method,
            "visual_source": request.visual_source,
            "footage_provider": ({
                "name": footage_provider.name,
                "mode": effective_provider_mode,
                "fallback_warnings": fallback_warnings,
            } if footage_provider else None),
            "image_generation": image_generation_report,
            "fallback_warnings": fallback_warnings,
            "scenes": [
                {
                    **scene,
                    "clip": {
                        key: value
                        for key, value in scene["clip"].items()
                        if key != "file_path"
                    },
                }
                for scene in scenes
            ],
        }
        result = {
            "job_id": job_id,
            "videos": videos,
            "captions": "captions.srt",
            "timeline": "timeline.json",
            "manifest": "manifest.json",
            "rights_report": "rights_review_report.json",
            "image_generation_report": "image_generation_report.json" if image_generation_report else None,
            "narration": audio_path.name,
            "provider": "AI image generation" if image_generator else "Local media catalogue" if effective_provider_mode == "local" else footage_provider.name,
            "provider_mode": effective_provider_mode,
            "visual_source": request.visual_source,
            "fallback_warnings": fallback_warnings,
            "narration_provider": data.get("narration_provider", "user-supplied audio"),
            "license_note": "See each scene's source, licence, and attribution details in timeline.json; review provider terms for your use case.",
            "created_at": utc_now(),
        }
        if image_generation_report:
            result["image_generation"] = image_generation_report
        # Report rights only for clips present in this render. Provider assets
        # without an explicit use-rights confirmation remain pending review.
        used_media = []
        for scene in scenes:
            clip = scene["clip"]
            media_path = Path(clip.get("file_path", ""))
            try:
                report_path = media_path.resolve().relative_to(folder.resolve()).as_posix()
            except (ValueError, OSError):
                report_path = media_path.name
            used_media.append({
                "id": clip.get("asset_id"),
                "path": report_path,
                "media_type": clip.get("media_type", "video"),
                "source_url": clip.get("source_url"),
                "provider": clip.get("provider"),
                "provider_source": clip.get("provider_source"),
                "creator": clip.get("creator"),
                "license_name": clip.get("license_name"),
                "license_url": clip.get("license_url"),
                "attribution_required": clip.get("attribution_required"),
                "usage_rights_confirmed": clip.get("usage_rights_confirmed"),
            })
        rights_report = media_library.rights_review_report({"items": used_media})
        rights_report["job_id"] = job_id
        rights_report["report_path"] = str(folder / "rights_review_report.json")
        (folder / "rights_review_report.json").write_text(encode_json(rights_report), encoding="utf-8")
        manifest = {
            **result,
            "input": {key: value for key, value in data.items() if key != "audio_url"},
            "scenes": timeline["scenes"],
            "rights_summary": {
                "media_items": rights_report["media_items"],
                "rights_approved": rights_report["rights_approved"],
                "rights_review_required": rights_report["rights_review_required"],
                "rights_rejected": rights_report["rights_rejected"],
            },
            "audio": audio_metadata,
            "settings": {
                "aspect_ratios": request.aspect_ratios,
                "captions_enabled": request.captions_enabled,
                "visual_style": request.visual_style,
                "voice": data.get("selected_voice", request.voice),
                "visual_source": request.visual_source,
            },
        }
        (folder / "timeline.json").write_text(encode_json(timeline), encoding="utf-8")
        (folder / "manifest.json").write_text(encode_json(manifest), encoding="utf-8")
        update_job(
            job_id,
            status="completed",
            progress=100,
            current_stage="completed",
            result_json=encode_json(result),
            error_json=None,
            timeline_json=encode_json(timeline),
            completed_at=utc_now(),
        )
        _remove_render_intermediates(folder)
    except JobProcessingError as error:
        update_job(
            job_id,
            status="failed",
            current_stage="failed",
            error_json=encode_json({"code": error.code, "message": error.message}),
            completed_at=utc_now(),
        )
    except Exception:
        logger.exception("Unexpected error while processing job %s", job_id)
        update_job(
            job_id,
            status="failed",
            current_stage="failed",
            error_json=encode_json(
                {"code": "internal_processing_error", "message": "The job failed unexpectedly. Check server logs."}
            ),
            completed_at=utc_now(),
        )


def process_job(job_id: str, data: dict[str, Any], uploaded_audio: str | None = None) -> None:
    try:
        _process(job_id, data, uploaded_audio)
    finally:
        if uploaded_audio:
            try:
                Path(uploaded_audio).unlink(missing_ok=True)
            except OSError:
                logger.warning("Could not remove temporary uploaded audio file")
